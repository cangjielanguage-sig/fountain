-- =============================================================================
-- f_llm 全部表结构（PostgreSQL 版，含 OpenGauss 兼容子集）
--
-- 配套文件：tables-mysql.sql（列定义保持一致，只允许类型/自增/索引语法不同）
-- 依赖扩展：pgvector（python 包名 pgvector，扩展名 vector），版本 >= 0.7
--   CREATE EXTENSION IF NOT EXISTS vector;   -- 需要超级用户，按库执行一次
--
-- 维护约定：
--   1. 两个文件必须同步改；改列先改这里，再同步 MySQL 文件与 src/model/po
--   2. 金额/时间统一：余额金额是「元」（上游按分的在解析层换算），时间用 timestamp
--   3. 不使用外键：跨库移植与批量导入都更省事，一致性由业务层保证
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. 模型配置（既有表，llm_conf.postgres.sql 已并入本文件）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_conf (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider         VARCHAR(64)  NOT NULL DEFAULT '',
  llm_name         VARCHAR(128) NOT NULL DEFAULT '',
  actual_llm_name  VARCHAR(128) NOT NULL DEFAULT '',
  llm_url          VARCHAR(512) NOT NULL DEFAULT '',
  auth             VARCHAR(512) NOT NULL DEFAULT '',
  temperature      DOUBLE PRECISION NOT NULL DEFAULT -1,
  always_thinking  BOOLEAN      NOT NULL DEFAULT FALSE,
  conf             TEXT         NULL,
  enabled          BOOLEAN      NOT NULL DEFAULT TRUE,
  weight           BIGINT       NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_llm_conf_name ON llm_conf (llm_name, enabled);

-- -----------------------------------------------------------------------------
-- 2. 智能体、技能、记忆摘要、待办、token 用量（既有表，列以 model/po 为准）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS agents (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_name  VARCHAR(128) NOT NULL DEFAULT '',
  agent       TEXT         NULL,
  acceptable  TEXT         NULL,
  producings  TEXT         NULL,
  category    VARCHAR(64)  NOT NULL DEFAULT '',
  tag         VARCHAR(64)  NOT NULL DEFAULT '',
  llm_type    VARCHAR(32)  NOT NULL DEFAULT '',
  llm_name    VARCHAR(128) NOT NULL DEFAULT '',
  pruner      VARCHAR(256) NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_agents_name ON agents (agent_name);

CREATE TABLE IF NOT EXISTS skills (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_id       BIGINT       NOT NULL DEFAULT 0,
  accepted_event VARCHAR(64)  NOT NULL DEFAULT '',
  returned_event VARCHAR(64)  NOT NULL DEFAULT '',
  title          VARCHAR(256) NOT NULL DEFAULT '',
  metadata       TEXT         NULL,
  details        TEXT         NULL,
  functions      TEXT         NULL,
  version        INT          NOT NULL DEFAULT 1,   -- 技能自演进版本（§10.4）
  skill_type     VARCHAR(32)  NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_skills_agent ON skills (agent_id, accepted_event);

CREATE TABLE IF NOT EXISTS skill_references (
  skill_title VARCHAR(256) NOT NULL DEFAULT '',
  title       VARCHAR(256) NOT NULL DEFAULT '',
  content     TEXT         NULL
);
CREATE INDEX IF NOT EXISTS idx_skill_ref_title ON skill_references (skill_title);

CREATE TABLE IF NOT EXISTS memory_summaries (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind    VARCHAR(32) NOT NULL DEFAULT '',
  content TEXT        NULL
);

CREATE TABLE IF NOT EXISTS agent_todo (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(256) NOT NULL DEFAULT '',
  content     TEXT         NULL,
  status      VARCHAR(32)  NOT NULL DEFAULT 'pending',
  predecessor TEXT         NULL
);

CREATE TABLE IF NOT EXISTS llm_token_usage (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  llm_id            BIGINT      NOT NULL DEFAULT 0,
  agent_id          BIGINT      NOT NULL DEFAULT 0,
  session           VARCHAR(128) NOT NULL DEFAULT '',
  prompt_tokens     BIGINT      NOT NULL DEFAULT 0,
  completion_tokens BIGINT      NOT NULL DEFAULT 0,
  total_tokens      BIGINT      NOT NULL DEFAULT 0,
  cached_tokens     BIGINT      NOT NULL DEFAULT 0,
  usage_time        BIGINT      NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_usage_agent ON llm_token_usage (agent_id, usage_time);

-- -----------------------------------------------------------------------------
-- 3. 记忆（新增）
--    namespace = 'global' 或 'ws-{workspaceId}'，承担「工作空间 / 全局」两个维度
--    唯一键用 (user_id, namespace, title)：同空间同标题幂等覆盖
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_memory (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT       NOT NULL DEFAULT 0,
  namespace   VARCHAR(32)  NOT NULL,
  title       VARCHAR(128) NOT NULL,
  content     TEXT         NULL,
  kind        VARCHAR(32)  NOT NULL DEFAULT 'note',   -- note|fact|preference|task|doc|knowledge|session，运行期可扩展
  save_time   TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  update_time TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT uk_memory_user_ns_title UNIQUE (user_id, namespace, title)
);
CREATE INDEX IF NOT EXISTS idx_memory_ns_time ON llm_memory (user_id, namespace, save_time DESC);

-- 记忆种类：预定义 7 值（user_id=0 全局），自定义 kind 归属用户；预定义行不允许删除（API 层拒绝）
CREATE TABLE IF NOT EXISTS llm_memory_kind (
  user_id     BIGINT      NOT NULL DEFAULT 0,
  kind        VARCHAR(32) NOT NULL,
  predefined  BOOLEAN     NOT NULL DEFAULT FALSE,
  weight      DOUBLE PRECISION NOT NULL DEFAULT 0.8,   -- 检索打分权重 0~1，自动记忆更低
  create_time TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  PRIMARY KEY (user_id, kind)
);
INSERT INTO llm_memory_kind (user_id, kind, predefined, weight) VALUES
  (0, 'note', TRUE, 0.9), (0, 'fact', TRUE, 1.0), (0, 'preference', TRUE, 1.0),
  (0, 'task', TRUE, 0.6), (0, 'doc', TRUE, 0.8), (0, 'knowledge', TRUE, 0.8),
  (0, 'session', TRUE, 0.3)
ON CONFLICT (user_id, kind) DO NOTHING;

-- 记忆事件（§5.5 事件溯源）：先落事件再异步消费，processed=false 的会被重试
CREATE TABLE IF NOT EXISTS llm_memory_event (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT      NOT NULL,
  session     VARCHAR(64) NOT NULL,
  task_name   VARCHAR(64) NOT NULL DEFAULT '',
  event_type  VARCHAR(32) NOT NULL,
  step_id     VARCHAR(64) NOT NULL DEFAULT '',
  payload     TEXT        NOT NULL,
  processed   BOOLEAN     NOT NULL DEFAULT FALSE,
  retry_count INT         NOT NULL DEFAULT 0,
  event_time  TIMESTAMP   NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_event_pending ON llm_memory_event (processed, event_time);
CREATE INDEX IF NOT EXISTS idx_event_session ON llm_memory_event (user_id, session, event_time);

-- 标题与正文各一套向量；colbert 只做重排，不建索引
-- 维度 1024 与 bge-m3 对齐；换模型时必须同步改列宽并重建索引
CREATE TABLE IF NOT EXISTS llm_memory_vector (
  memory_id      BIGINT PRIMARY KEY,
  model          VARCHAR(64) NOT NULL,
  title_dense    vector(1024),
  content_dense  vector(1024),
  -- colbert：二进制 f32[]，布局 count(Int32 LE) + count*dim*Float32 LE；不存 JSON（体积约 3 倍）
  title_colbert  BYTEA,
  content_colbert BYTEA,
  has_sparse     BOOLEAN NOT NULL DEFAULT FALSE,
  has_colbert    BOOLEAN NOT NULL DEFAULT FALSE,
  update_time    TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

-- 稀疏向量落地为倒排表：四种数据库语义一致，且天然按 (user_id, namespace) 隔离
CREATE TABLE IF NOT EXISTS llm_memory_token (
  memory_id BIGINT      NOT NULL,
  user_id   BIGINT      NOT NULL,
  namespace VARCHAR(32) NOT NULL,
  field     CHAR(1)     NOT NULL,             -- 't' 标题 / 'c' 正文
  token     BIGINT      NOT NULL,             -- bge-m3 token id
  weight    DOUBLE PRECISION NOT NULL,
  PRIMARY KEY (memory_id, field, token)
);
CREATE INDEX IF NOT EXISTS idx_memory_token_lookup
  ON llm_memory_token (user_id, namespace, field, token);

-- 向量索引：HNSW + 余弦距离（pgvector 0.7+ 支持 vector 的 HNSW）
CREATE INDEX IF NOT EXISTS idx_memory_title_dense
  ON llm_memory_vector USING hnsw (title_dense vector_cosine_ops);
CREATE INDEX IF NOT EXISTS idx_memory_content_dense
  ON llm_memory_vector USING hnsw (content_dense vector_cosine_ops);

-- -----------------------------------------------------------------------------
-- 4. 人设（新增）
--    character_key 指向代码里的预定义人设；prompts 存最终生效文本
--    每个用户一条，未落库时按 default（不注入 system）处理
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_character (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT      NOT NULL DEFAULT 0,
  character_key VARCHAR(32) NOT NULL DEFAULT 'default',
  prompts       TEXT        NULL,
  update_time   TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT uk_character_user UNIQUE (user_id)
);

-- -----------------------------------------------------------------------------
-- 4.1 人格绑定（工作空间/任务/流程），只存 key 不存提示词正文
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_character_binding (
  user_id       BIGINT      NOT NULL,
  scope_type    VARCHAR(16) NOT NULL,   -- workspace | task | flow
  scope_id      VARCHAR(64) NOT NULL,
  character_key VARCHAR(32) NOT NULL,
  update_time   TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  PRIMARY KEY (user_id, scope_type, scope_id)
);

-- -----------------------------------------------------------------------------
-- 4.2 通道绑定（微信/企微/飞书/钉钉/QQ/邮件）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_channel_binding (
  user_id      BIGINT       NOT NULL,
  channel      VARCHAR(16)  NOT NULL,
  external_id  VARCHAR(128) NOT NULL,
  display_name VARCHAR(128) NOT NULL DEFAULT '',
  auto_send    BOOLEAN      NOT NULL DEFAULT FALSE,
  enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
  update_time  TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  PRIMARY KEY (user_id, channel, external_id)
);

-- -----------------------------------------------------------------------------
-- 4.3 技能版本（升级前存旧版本，支持回滚）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_skill_version (
  skill_id     BIGINT       NOT NULL,
  version      INT          NOT NULL,
  details      TEXT         NOT NULL,
  functions    TEXT         NOT NULL,
  change_note  VARCHAR(256) NOT NULL DEFAULT '',
  created_time TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  PRIMARY KEY (skill_id, version)
);

-- -----------------------------------------------------------------------------
-- 5. loom 流程定义（新增）
--    JitFunction 不可序列化：这里存计划与源码，启动时重新编译
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_loom_flow (
  name         VARCHAR(64) PRIMARY KEY,
  description  TEXT,
  plan_json    TEXT        NOT NULL,
  flow_source  TEXT        NOT NULL,
  step_sources TEXT        NOT NULL,
  status       VARCHAR(16) NOT NULL DEFAULT 'pending',   -- clarifying | pending | compiled | failed | blocked
  round        INT         NOT NULL DEFAULT 0,           -- 已进行的澄清轮次
  questions_json TEXT,                                   -- status=clarifying 时的待答问题
  tools        TEXT,
  mcps         TEXT,
  created_time TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  update_time  TIMESTAMP   NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);
CREATE INDEX IF NOT EXISTS idx_loom_status ON llm_loom_flow (status, update_time);

-- -----------------------------------------------------------------------------
-- 6. 提示词版本（元数据族，PG/MySQL/f_store 三实现）
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS llm_prompt (
  name        VARCHAR(128) NOT NULL,
  version     INT          NOT NULL,
  content     TEXT         NOT NULL,
  update_time TIMESTAMP    NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  PRIMARY KEY (name, version)
);