CREATE OR REPLACE FUNCTION update_modified_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.update_time = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
----
CREATE OR REPLACE FUNCTION update_used_count()
RETURNS TRIGGER AS $$
BEGIN
    NEW.used_count = NEW.used_count + 1;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
