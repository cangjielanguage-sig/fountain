create table knowledge(
    id bigint GENERATED BY DEFAULT AS IDENTITY, 
    code_lang varchar(8) not null, 
    kind varchar(16) not null,
    md5 varchar(32) not null,
    source varchar(128) not null, 
    entire boolean not null,
    title varchar(255) NOT NULL,
    content text NOT NULL,
    used_count int NOT NULL,
    save_time timestamptz,
    update_time timestamptz,
    embedding VECTOR(1024)
);
ALTER TABLE knowledge ADD CONSTRAINT knowledge_pkey PRIMARY KEY (id);  
ALTER TABLE knowledge ADD COLUMN search_vector tsvector
GENERATED ALWAYS AS (
    setweight(to_tsvector('chinese_english', COALESCE(title, '')), 'A') ||
    setweight(to_tsvector('chinese_english', COALESCE(content, '')), 'B')
) STORED;
CREATE INDEX idx_knowledge_search_vector ON knowledge USING GIN(search_vector);
CREATE INDEX ON knowledge USING hnsw (embedding vector_cosine_ops) WITH (m = 16, ef_construction = 64);
create index idx_knowledge_codelang on knowledge(code_lang, kind, source, entire);
create unique index uk_knowledge_md5 on knowledge (md5, code_lang, kind);
comment on column knowledge.code_lang is '代码文件的扩展名';
comment on column knowledge.kind is 'STD API SYNTAX EXPERIENCE CODESPEC ARTICLE COPYRIGHT SKILL_RESOURCE SKILL_REFERENCE SKILL_TOOL, STD、API、SYNTAX、CODESPEC和EXPERIENCE跟语言强相关，ARTICLE不一定跟语言相关，STD是标准库文档，API工具库文档，SYNTAX是语言特性，ARTICLE是技术文章，EXPERIENCE是犯过的错误、解决过的BUG、git提交的差异和提交信息的总结等，CODESPEC是代码规范，COPYRIGHT是版权声明，COPYRIGHT对应的code_lang是开源协议名，SKILL_RESOURCE是技能资源，SKILL_REFERENCE是技能参考资料，SKILL_TOOL是技能需要的工具';
comment on column knowledge.md5 is 'content的md5值，用于去重';
comment on column knowledge.source is '来源，对于STD API SYNTAX类型source的值就是版本号，对于ARTICLE source是URL，其它类型source是空字符串';
comment on column knowledge.entire is '是否整个文件，true：整个文档，false：只是一部分文档。把文档按标题拆分，方便只给llm提供需要的那部分';
comment on column knowledge.title is '对于SKILL_TOOL 此列是工具名';
comment on column knowledge.content is '对于SKILL_TOOL此列是JSON格式的工具描述{"description":"详细描述"，"parameters":[{"type":"DECIMAL", "properties":{"paramName":{"type":"DECIMAL", "decription":"参数的描述"},...}},...]}，SKILL_TOOL.params[].type是数据类型，可选值：DECIMAL STRING DATETIME DURATION BOOL OBJECT DECIMAL_ARRAY STRING_ARRAY DATETIME_ARRAY DURATION_ARRAY BOOL_ARRAY OBJECT_ARRAY；其它知识类型此列是markdown格式';
comment on column knowledge.save_time is '保存时间';
